r"""
AI Deep-Sea Survey & Search Party Mission Report Generator
==========================================================
Generates an AI-powered technical and operational search mission report
tailored for marine search party organizations, coast guard units,
AUV/ROV inspection teams, and underwater archaeological expeditions.
"""

import datetime
from typing import Dict, Any, List, Optional


class AIReportGenerator:
    """
    Generates structured AI technical evaluation reports
    in Markdown and formatted HTML formats for search party organizations.
    """

    @staticmethod
    def generate_markdown_report(
        record_data: Dict[str, Any],
        enhancement_data: Optional[Dict[str, Any]] = None
    ) -> str:
        """Generates comprehensive markdown search party mission report."""
        rec = record_data
        enh = enhancement_data or {}

        depth_m = float(rec.get("depth_m", 150.0))
        p_atm = float(rec.get("total_pressure_atm", 1.0))
        p_kpa = float(rec.get("pressure_kpa", 101.3))
        safety = str(rec.get("safety_status", "SAFE"))
        light_zone = str(rec.get("light_zone", "Euphotic Zone"))
        ambient_lux = float(rec.get("ambient_lux", 1000.0))
        red_loss = float(rec.get("red_loss_pct", 95.0))
        raw_uciqe = float(rec.get("raw_uciqe", 0.0))
        enh_uciqe = float(enh.get("enhanced_uciqe", 0.0))
        uciqe_gain = enh_uciqe - raw_uciqe

        mission_code = rec.get("mission_code", "SAR-OFFSHORE-01")
        gps_coords = rec.get("gps_coords", "17.3850 N, 78.4867 E")
        search_org = rec.get("search_org", "Marine Search & Rescue Unit")
        target_type = rec.get("target_type", "all")
        rov_unit_id = rec.get("rov_unit_id", "ROV-EXPLORER-01")

        total_loss = float(enh.get("joint_loss_L", 0.0))
        l_rec = float(enh.get("loss_rec", 0.0))
        l_perc = float(enh.get("loss_perc", 0.0))
        l_det = float(enh.get("loss_det", 0.0))
        l_stage = float(enh.get("loss_stage", 0.0))

        detections = []
        if enh.get("detections_json"):
            import json
            try:
                detections = json.loads(enh["detections_json"])
            except Exception:
                detections = []

        report_id = f"SAR-RPT-{rec.get('record_id', datetime.datetime.now().strftime('%Y%m%d%H%M%S'))}"
        timestamp = rec.get("timestamp", datetime.datetime.now().isoformat())

        md = f"""# MARINE SEARCH PARTY & UNDERWATER SURVEY MISSION REPORT
**Report Reference:** `{report_id}`  
**Mission Code:** `{mission_code}`  
**Search Organization:** `{search_org}`  
**Vessel / Deployable Unit:** `{rov_unit_id}`  
**Target Category:** `{target_type.upper()}`  
**GPS Coordinates:** `{gps_coords}`  
**Capture Timestamp:** `{timestamp}`  
**Sensor Housing Safety:** `{safety}`  

---

## 1. Mission Overview & Search Sector
This tactical inspection report was generated by the **DeepSea Vision AI Platform** for field search party units and oceanographic survey organizations. The target area was surveyed at depth **{depth_m:.1f} meters** under challenging optical degradation conditions.

- **Primary Search Target:** `{target_type.capitalize()}`
- **Submersible Depth:** `{depth_m:.1f} m` (Survey Envelope: `0.0 m` - `500.0 m`)
- **Ambient Hydrostatic Pressure:** `{p_atm:.2f} atm` (`{p_kpa:.1f} kPa`)
- **Operational Safety Verdict:** **{safety}**

---

## 2. Environmental & Hydrostatic Diagnostics (0m - 500m)
The imaging sensor operated under the following physical parameters:

- **Hydrostatic Law Calculation:**
  $$\\displaystyle P(d) = P_0 + \\frac{{\\rho \\cdot g \\cdot d}}{{101325}} = 1.0 + \\frac{{1025 \\times 9.80665 \\times {depth_m:.1f}}}{{101325}} = {p_atm:.2f}\\text{{ atm}}$$
- **Optical Light Zone:** `{light_zone}`
- **Ambient Illumination:** `{ambient_lux:.1f} lux`
- **Spectral Red Attenuation:** `{red_loss:.1f}% extinction` (Absorption coefficient: $\\beta_R = 0.350\\,\\text{{m}}^{{-1}}$)
- **Housing Integrity Status:** Rated to **56.0 atm (~550m)**. Housing structural margin: **{(56.0 - p_atm):.2f} atm reserve**.

---

## 3. Deep Unfolding Physical Restoration Performance

### A. Optical Degradation Inversion
Degradation adhered to:
$$\\displaystyle I(x) = J(x) \\cdot t(x) + B \\cdot (1 - t(x))$$
Direct transmission $t(x)$ was severely attenuated by turbidity and depth. Backscatter veil $B$ dominated the optical pathway.

### B. Iterative Physics Unrolling
The system minimized:
$$\\displaystyle J^* = \\arg\\min_J \\frac{{1}}{{2}} \\| I - (J \\cdot t + B(1 - t)) \\|^2 + \\lambda R(J) + \\mu L_{{\\text{{det}}}}(J)$$
- **Stage 1 (Red Spectral Restoration):** Reconstituted missing red wavelengths, lifting visibility on submerged objects and living organisms.
- **Stage 2 (Backscatter Veil Removal):** Inverted the diffuse haze veil $B(1-t)$ and recovered local contrast.
- **Stage 3 (Detector-Guided Sharpening):** Coupled high-frequency edge gradients with detector guidance features $F_{{\\text{{det}}}}$ to enhance boundary contrast.

---

## 4. Target Detection & Search Party Evidence Log
Target enumeration on enhanced imagery identified **{len(detections)} contact(s)**:

| Contact # | Target Class | Confidence | Bounding Box [x1, y1, x2, y2] | Search Sector Assessment |
|---|---|---|---|---|
"""
        if detections:
            for i, d in enumerate(detections, 1):
                c_name = d.get("class_name", "Unknown").capitalize()
                score = d.get("score", 0.0)
                box = d.get("box", [0, 0, 0, 0])
                box_str = f"[{int(box[0])}, {int(box[1])}, {int(box[2])}, {int(box[3])}]"
                md += f"| {i} | **{c_name}** | `{score:.2f}` ({score*100:.1f}%) | `{box_str}` | High confidence visual match within sector |\n"
        else:
            md += "| - | *No confirmed contacts* | `-` | `-` | *Zero target signatures detected in current frame* |\n"

        md += f"""
---

## 5. Quantitative Quality Assessment & Multi-Task Loss
- **UCIQE (Color Quality Evaluation):**
  - Raw Degraded: `{raw_uciqe:.4f}`
  - Enhanced Result: `{enh_uciqe:.4f}`
  - **Quality Gain:** `{('+' if uciqe_gain >= 0 else '')}{uciqe_gain:.4f}`
- **Joint Loss Breakdown:**
  $$\\displaystyle L = L_{{\\text{{rec}}}} + \\alpha L_{{\\text{{perc}}}} + \\beta L_{{\\text{{det}}}} + \\gamma L_{{\\text{{stage}}}} = {total_loss:.4f}$$
  - $L_{{\\text{{rec}}}}$: `{l_rec:.4f}` | $\\alpha L_{{\\text{{perc}}}}$: `{l_perc:.4f}` | $\\beta L_{{\\text{{det}}}}$: `{l_det:.4f}` | $\\gamma L_{{\\text{{stage}}}}$: `{l_stage:.4f}`

---

## 6. Search Party Tactical Recommendations
1. **Target Verification:** Contacts identified with $>90\\%$ confidence should be prioritized for ROV acoustic tagging or physical recovery.
2. **Search Grid Expansion:** If visibility remains above UCIQE `{enh_uciqe:.4f}`, proceed along the planned survey transect at 1.5 knots.
3. **Safety Telemetry:** At {depth_m:.1f}m ({p_atm:.2f} atm), ROV tether strain and camera housing remain well within rated specifications.
"""
        return md


